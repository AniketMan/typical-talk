/**
 * Everything a stranger can send us, checked in one place.
 *
 * SQL injection is not among the risks here: every query uses bound
 * parameters, so a handle of "'; DROP TABLE users; --" is stored and compared
 * as that literal text and never parsed as SQL. These rules exist for the
 * other reasons: impersonation, unreadable or invisible names, and abuse.
 */

/** Handles someone could use to pass as the app, its staff, or a system. */
const RESERVED_HANDLES = new Set([
  "admin", "administrator", "root", "superuser", "sudo", "system", "sysadmin",
  "support", "help", "helpdesk", "security", "moderator", "mod", "staff",
  "team", "official", "verified", "typicaltalk", "typical_talk", "typical",
  "apple", "appstore", "billing", "payments", "noreply", "no_reply", "postmaster",
  "abuse", "legal", "privacy", "info", "contact", "about", "settings", "account",
  "login", "signin", "signup", "register", "password", "me", "you", "null",
  "undefined", "anonymous", "everyone", "all", "api", "www", "app", "invite",
  "invites", "talk", "talks", "user", "users", "test", "demo",
]);

/** Invisible or direction-changing characters, used to disguise text. */
// eslint-disable-next-line no-misleading-character-class
const INVISIBLE = /[\u0000-\u001F\u007F-\u009F­͏؜ᅟᅠ឴឵᠋-᠎​-‏‪-‮⁠-⁯﻿￹-￻]/u;

const INVISIBLE_GLOBAL = new RegExp(INVISIBLE.source, "gu");

/** Emoji and pictographs. Fine in a take, not in a name people must read. */
const PICTOGRAPHIC = /\p{Extended_Pictographic}|\p{Emoji_Presentation}/u;

export interface Checked<T> {
  value?: T;
  error?: string;
}

/**
 * A handle: lower case ASCII, 3 to 20 characters.
 *
 * Underscores may separate but not lead, trail or double up, which stops
 * "a__dmin" and "_admin_" style near-misses. One letter is required so a
 * handle cannot be only digits and read as an id.
 */
export function checkHandle(raw: unknown): Checked<string> {
  if (typeof raw !== "string") return { error: "Give a handle." };
  const handle = raw.trim().toLowerCase().replace(/^@+/, "");

  if (handle.length < 3 || handle.length > 20) {
    return { error: "Handles are 3 to 20 characters." };
  }
  if (!/^[a-z0-9_]+$/.test(handle)) {
    return { error: "Handles use letters, numbers and underscores only." };
  }
  if (!/[a-z]/.test(handle)) {
    return { error: "Handles need at least one letter." };
  }
  if (handle.startsWith("_") || handle.endsWith("_") || handle.includes("__")) {
    return { error: "Underscores cannot start, end or repeat in a handle." };
  }
  if (RESERVED_HANDLES.has(handle)) {
    return { error: "That handle is reserved." };
  }
  return { value: handle };
}

/**
 * A display name: 1 to 40 characters of ordinary text.
 *
 * Letters from any script are allowed, because people's names are not ASCII.
 * Emoji, control characters and direction overrides are not, because a name
 * is read by other people and must not be able to disguise itself or break
 * the line it sits on.
 */
export function checkName(raw: unknown): Checked<string> {
  if (typeof raw !== "string") return { error: "Give a name." };
  const name = raw.replace(/\s+/g, " ").trim();

  if (name.length === 0) return { error: "A name cannot be empty." };
  if (name.length > 40) return { error: "Names are at most 40 characters." };
  if (INVISIBLE.test(name)) return { error: "That name contains invisible characters." };
  if (PICTOGRAPHIC.test(name)) return { error: "Names cannot contain emoji." };
  if (!/\p{L}|\p{N}/u.test(name)) return { error: "Names need at least one letter." };
  return { value: name };
}

/** Invite codes are generated by us, so anything else is a probe. */
export function checkInviteCode(raw: unknown): Checked<string> {
  if (typeof raw !== "string") return { error: "Give an invite code." };
  const code = raw.trim().toLowerCase();
  if (!/^[a-z2-9]{8}$/.test(code)) return { error: "That is not an invite code." };
  return { value: code };
}

/**
 * Ids are UUIDs. They are lower cased here because Swift writes them upper
 * case, and the same id must not exist twice in two spellings.
 */
export function checkID(raw: unknown): Checked<string> {
  if (typeof raw !== "string") return { error: "Missing id." };
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(raw)) {
    return { error: "Not a valid id." };
  }
  return { value: raw.toLowerCase() };
}

/** An APNs device token is hex; anything else is not one. */
export function checkDeviceToken(raw: unknown): Checked<string> {
  if (typeof raw !== "string") return { error: "Missing device token." };
  const token = raw.trim().toLowerCase();
  if (!/^[0-9a-f]{32,200}$/.test(token)) return { error: "Not a device token." };
  return { value: token };
}

const REPORT_REASONS = new Set(["harassment", "nudity", "violence", "spam", "other"]);

export function checkReportReason(raw: unknown): Checked<string> {
  if (typeof raw !== "string" || !REPORT_REASONS.has(raw)) {
    return { error: "Pick a reason for the report." };
  }
  return { value: raw };
}

/** Free text the reporter adds. Kept short and stripped of control characters. */
export function checkDetails(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  const text = raw.replace(INVISIBLE_GLOBAL, "").trim().slice(0, 500);
  return text.length > 0 ? text : null;
}

/** Escapes text before it goes anywhere near HTML. */
export function escapeHTML(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
